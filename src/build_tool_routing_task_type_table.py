#!/usr/bin/env python3
"""Build a compact tool-call task-type table from evaluated routing scores."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from benchmark_utils import REPO_ROOT
from build_potential_analyses import MODEL_NAMES


OUTPUT_DIR = REPO_ROOT / "paper" / "generated" / "potential"
EVALUATION_DIR = REPO_ROOT / "results" / "evaluation"

OPEN_MODEL_ORDER = [
    "gemma-4-31b",
    "qwen3.6-35b-a3b",
    "gpt-oss-20b-low",
    "gpt-oss-20b-medium",
    "gpt-oss-20b",
    "gemma-4-26b-a4b",
    "bonsai-8b",
]
API_MODEL_ORDER = [
    "gpt-5.6-luna-medium",
    "gpt-5.6-luna-none",
    "gpt-5.4-mini-medium",
    "gpt-5.4-mini-none",
    "gpt-5.4-nano-medium",
    "gpt-5.4-nano-none",
]
TASK_TYPES = {
    "single_stat": ("single_strict", "single_accepted"),
    "pairwise_compare": ("pairwise_strict", "pairwise_accepted"),
    "topk_differences": ("topk_strict", "topk_accepted"),
}
DISPLAY_COLUMNS = [
    "single_strict",
    "single_accepted",
    "pairwise_strict",
    "pairwise_accepted",
    "topk_strict",
    "topk_accepted",
]


def read_task_type_scores(model_label: str) -> pd.DataFrame:
    path = EVALUATION_DIR / f"paper_tool_{model_label}_tool_routing_by_task_type.csv"
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


def collect_rows() -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for group, model_order in [
        ("Open-weight / local", OPEN_MODEL_ORDER),
        ("GPT series / API", API_MODEL_ORDER),
    ]:
        for model_label in model_order:
            scores = read_task_type_scores(model_label)
            row: dict[str, Any] = {
                "group": group,
                "model_label": model_label,
                "Model": MODEL_NAMES.get(model_label, model_label),
            }
            for task_type, (strict_col, accepted_col) in TASK_TYPES.items():
                task_rows = scores[scores["tool_task_type"].astype(str).eq(task_type)] if not scores.empty else scores
                if task_rows.empty:
                    row[strict_col] = np.nan
                    row[accepted_col] = np.nan
                    continue
                row[strict_col] = float(task_rows["strict_routing_accuracy"].iloc[0]) * 100.0
                row[accepted_col] = float(task_rows["routing_accuracy"].iloc[0]) * 100.0
            rows.append(row)
    return pd.DataFrame(rows)


def fmt(value: Any) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "--"
    if not np.isfinite(number):
        return "--"
    return f"{number:.1f}"


def row_to_latex(row: pd.Series, *, bold: bool = False) -> str:
    cells = [str(row["Model"])]
    for column in DISPLAY_COLUMNS:
        value = fmt(row[column])
        cells.append(f"\\textbf{{{value}}}" if bold and value != "--" else value)
    return " & ".join(cells) + " \\\\"


def write_latex_table(frame: pd.DataFrame) -> None:
    macro = {"Model": "Macro average"}
    for column in DISPLAY_COLUMNS:
        macro[column] = frame[column].mean(skipna=True)
    macro_row = pd.Series(macro)

    lines = [
        "% Auto-generated by src/build_tool_routing_task_type_table.py",
        "\\begin{table}[!h]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3.2pt}",
        "\\renewcommand{\\arraystretch}{1.05}",
        (
            "\\caption{\\textbf{Tool-calling performance by task type.} Strict "
            "accuracy requires the exact reference tool and arguments, while "
            "accepted accuracy allows pre-defined equivalent arguments that "
            "produce the same deterministic result.}"
        ),
        "\\label{tab:tool-call-task-type}",
        "\\begin{tabular}{@{}lrrrrrr@{}}",
        "\\toprule",
        (
            "& \\multicolumn{2}{c}{Single-image} & \\multicolumn{2}{c}{Pairwise} "
            "& \\multicolumn{2}{c}{Top-$k$} \\\\"
        ),
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(l){6-7}",
        "Model & Strict & Accepted & Strict & Accepted & Strict & Accepted \\\\",
        "\\midrule",
    ]

    for group_name in ["Open-weight / local", "GPT series / API"]:
        if group_name == "GPT series / API":
            lines.append("\\midrule")
        lines.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\emph{{{group_name}}}}} \\\\")
        group_rows = frame[frame["group"].eq(group_name)]
        for _, row in group_rows.iterrows():
            lines.append(row_to_latex(row))

    lines.extend(
        [
            "\\midrule",
            row_to_latex(macro_row, bold=True),
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
            "",
        ]
    )
    out_path = OUTPUT_DIR / "table_tool_routing_task_type_breakdown.tex"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path}")


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    table = collect_rows()
    csv_path = OUTPUT_DIR / "tool_routing_task_type_breakdown.csv"
    table.to_csv(csv_path, index=False)
    print(f"Wrote {csv_path}")
    write_latex_table(table)


if __name__ == "__main__":
    main()
